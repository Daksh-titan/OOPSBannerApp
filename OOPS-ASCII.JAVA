/**
 * OOPSBannerApp
 *
 * Prints "OOPS" in banner format using String.join()
 * for better memory efficiency and cleaner structure.
 *
 * @author Daksh Kumar
 * @version 3.0
 */
public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println(String.join(" ",
                "  *****  ",
                "  *****  ",
                "  ****** ",
                "  ****** "));

        System.out.println(String.join(" ",
                " *     * ",
                " *     * ",
                " *     * ",
                " *     * "));

        System.out.println(String.join(" ",
                " *     * ",
                " *     * ",
                " *     * ",
                " *       "));

        System.out.println(String.join(" ",
                " *     * ",
                " *     * ",
                "  ****** ",
                "  *****  "));

        System.out.println(String.join(" ",
                " *     * ",
                " *     * ",
                " *       ",
                "       * "));

        System.out.println(String.join(" ",
                " *     * ",
                " *     * ",
                " *       ",
                " *     * "));

        System.out.println(String.join(" ",
                "  *****  ",
                "  *****  ",
                " *       ",
                "  *****  "));
    }
}
